-- 01_roles_warehouses_databases.sql
-- Creates roles, warehouse, database, schemas, and grants for the portfolio lab.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS AADDATA_PLATFORM_ADMIN;
CREATE ROLE IF NOT EXISTS AADDATA_DATA_ENGINEER;
CREATE ROLE IF NOT EXISTS AADDATA_ANALYST;

GRANT ROLE AADDATA_DATA_ENGINEER TO ROLE AADDATA_PLATFORM_ADMIN;
GRANT ROLE AADDATA_ANALYST TO ROLE AADDATA_PLATFORM_ADMIN;

-- Replace <your_user_name> before running.
