SHOW STREAMS IN SCHEMA RAW;
SHOW TASKS IN SCHEMA CONTROL;

-- SnowPro notes:
-- Streams track table change data.
-- Tasks schedule SQL execution.
-- Serverless tasks are also available, but warehouse tasks are easier for first practice.

