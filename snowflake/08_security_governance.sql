CREATE OR REPLACE SECURE VIEW MART.VW_INVESTOR_HOLDING_SUMMARY AS
SELECT
  h.valuation_date,
  i.investor_id,
  i.investor_type,
  i.country_code,
  h.fund_id,
  h.market_value,
  h.currency_code
FROM MART.FACT_INVESTOR_HOLDING_DAILY h
JOIN MART.DIM_INVESTOR i
  ON h.investor_id = i.investor_id;

GRANT SELECT ON VIEW MART.VW_INVESTOR_HOLDING_SUMMARY TO ROLE AADDATA_ANALYST;

-- Monitoring examples.
SELECT *
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY(
  DATEADD('hour', -24, CURRENT_TIMESTAMP()),
  CURRENT_TIMESTAMP()
))
ORDER BY start_time DESC
LIMIT 50;

SHOW GRANTS TO ROLE AADDATA_ANALYST;

