USE ROLE AADDATA_PLATFORM_ADMIN;
USE WAREHOUSE WH_AADDATA_DEV;
USE DATABASE MF_TRANS_DEV;

CREATE OR REPLACE TAG CONTROL.DATA_CLASSIFICATION
  ALLOWED_VALUES 'PUBLIC', 'INTERNAL', 'CONFIDENTIAL', 'PII';

ALTER TABLE CURATED.INVESTOR
  MODIFY COLUMN first_name SET TAG CONTROL.DATA_CLASSIFICATION = 'PII';

ALTER TABLE CURATED.INVESTOR
  MODIFY COLUMN last_name SET TAG CONTROL.DATA_CLASSIFICATION = 'PII';

CREATE OR REPLACE MASKING POLICY CONTROL.MASK_INVESTOR_NAME AS (val STRING)
  RETURNS STRING ->
    CASE
      WHEN CURRENT_ROLE() IN ('AADDATA_PLATFORM_ADMIN', 'AADDATA_DATA_ENGINEER') THEN val
      ELSE '***MASKED***'
    END;

